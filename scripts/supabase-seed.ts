/**
 * Writes supabase/seed.sql from the bundled JSON (src/data/venues.json,
 * performers.json, events.json), matching supabase/migrations/.
 *
 *   npm run db:seed                 → supabase/seed.sql
 *   psql "$SUPABASE_DB_URL" -f supabase/seed.sql      (or: supabase db reset, which runs seed.sql)
 *
 * Re-runnable: venues, performers and events are upserted by id; each seeded
 * event's performers and offers are replaced. With --prune, events that are
 * not in events.json are deleted. Runs in one transaction.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { EventsFile, PerformersFile, VenuesFile } from '../src/types.ts';

const root = resolve(import.meta.dirname, '..');
const read = <T>(rel: string) => JSON.parse(readFileSync(resolve(root, rel), 'utf8')) as T;
const { venues } = read<VenuesFile>('src/data/venues.json');
const { performers } = read<PerformersFile>('src/data/performers.json');
const { events } = read<EventsFile>('src/data/events.json');
const prune = process.argv.includes('--prune');

/** SQL literal. Numbers and booleans as-is, null/undefined as NULL, strings quoted. */
export function lit(v: string | number | boolean | null | undefined): string {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') {
    if (!Number.isFinite(v)) throw new Error(`not a finite number: ${v}`);
    return String(v);
  }
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return `'${v.replace(/'/g, "''")}'`;
}

const rows = (list: string[]) => list.join(',\n  ');
const out: string[] = [
  '-- Generated by scripts/supabase-seed.ts. Do not edit; re-run npm run db:seed.',
  `-- ${venues.length} venues, ${performers.length} performers, ${events.length} events.`,
  'begin;',
  '',
];

out.push(
  `insert into public.venues (id, name, type, city, district, address, location, precision, osm_id, osm_url, verified) values\n  ${rows(
    venues.map(
      (v) =>
        `(${lit(v.id)}, ${lit(v.name)}, ${lit(v.type)}, ${lit(v.city)}, ${lit(v.district)}, ${lit(v.address)}, ` +
        `extensions.st_setsrid(extensions.st_makepoint(${lit(v.lng)}, ${lit(v.lat)}), 4326)::extensions.geography, ` +
        `${lit(v.precision)}, ${lit(v.osmId)}, ${lit(v.osmUrl)}, ${lit(v.verified)})`,
    ),
  )}\non conflict (id) do update set name = excluded.name, type = excluded.type, city = excluded.city,
  district = excluded.district, address = excluded.address, location = excluded.location,
  precision = excluded.precision, osm_id = excluded.osm_id, osm_url = excluded.osm_url, verified = excluded.verified;`,
  '',
);

out.push(
  `insert into public.performers (id, name, kind, genre) values\n  ${rows(
    performers.map((p) => `(${lit(p.id)}, ${lit(p.name)}, ${lit(p.kind)}, ${lit(p.genre)})`),
  )}\non conflict (id) do update set name = excluded.name, kind = excluded.kind, genre = excluded.genre;`,
  '',
);

if (prune) {
  out.push(
    events.length
      ? `delete from public.events where id not in (${events.map((e) => lit(e.id)).join(', ')});`
      : 'delete from public.events;',
    '',
  );
}

if (events.length > 0) {
  out.push(
    `insert into public.events (id, venue_id, title, category, starts_at, image_url, description) values\n  ${rows(
      events.map(
        (e) =>
          `(${lit(e.id)}, ${lit(e.venueId)}, ${lit(e.title)}, ${lit(e.category)}, ${lit(e.startsAt)}, ${lit(e.imageUrl)}, ${lit(e.description)})`,
      ),
    )}\non conflict (id) do update set venue_id = excluded.venue_id, title = excluded.title, category = excluded.category,
  starts_at = excluded.starts_at, image_url = excluded.image_url, description = excluded.description;`,
    '',
    `delete from public.event_performers where event_id in (${events.map((e) => lit(e.id)).join(', ')});`,
    `delete from public.offers where event_id in (${events.map((e) => lit(e.id)).join(', ')});`,
    '',
  );
  const eps = events.flatMap((e) => (e.performerIds ?? []).map((pid, i) => `(${lit(e.id)}, ${lit(pid)}, ${i})`));
  if (eps.length) out.push(`insert into public.event_performers (event_id, performer_id, position) values\n  ${rows(eps)};`, '');
  const offers = events.flatMap((e) =>
    e.offers.map(
      (o) =>
        `(${lit(e.id)}, ${lit(o.platform)}, ${lit(o.url)}, ${lit(o.price)}, ${lit(o.label)}, ${lit(o.available !== false)})`,
    ),
  );
  out.push(`insert into public.offers (event_id, platform, url, price, label, available) values\n  ${rows(offers)};`, '');
}

out.push('commit;', '');
mkdirSync(resolve(root, 'supabase'), { recursive: true });
writeFileSync(resolve(root, 'supabase/seed.sql'), out.join('\n'));
console.log(`Wrote supabase/seed.sql (${venues.length} venues, ${performers.length} performers, ${events.length} events${prune ? ', prune' : ''})`);
