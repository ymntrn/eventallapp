/**
 * Builds src/data/venues.json from the OSM venue database
 * (data/venues/eventall_venues.json).
 *
 *   npm run import:venues:db
 *
 * - Keeps the database ids (ank-…, ist-…).
 * - Maps the 14 database types to the app's VenueType (src/lib/venue-db.ts).
 * - Every venue starts with verified: false. A venue that is already
 *   verified: true in the current src/data/venues.json keeps the flag as long
 *   as its coordinates did not change, so re-importing never loses checks.
 * Overwrites src/data/venues.json. Run `npm run validate:data` afterwards.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { Venue, VenuesFile } from '../src/types.ts';
import { dbRowToVenue, type DbVenueRow } from '../src/lib/venue-db.ts';

const root = resolve(import.meta.dirname, '..');
const dbPath = resolve(root, 'data/venues/eventall_venues.json');
const outPath = resolve(root, 'src/data/venues.json');

const rows = JSON.parse(readFileSync(dbPath, 'utf8')) as DbVenueRow[];

const previous = new Map<string, Venue>();
if (existsSync(outPath)) {
  const file = JSON.parse(readFileSync(outPath, 'utf8')) as VenuesFile;
  for (const v of file.venues ?? []) previous.set(v.id, v);
}

const problems: string[] = [];
const venues: Venue[] = [];
let kept = 0;
let reset = 0;
for (const row of rows) {
  const prev = previous.get(row.id);
  const sameSpot = prev !== undefined && prev.lat === row.lat && prev.lng === row.lng;
  if (prev?.verified && sameSpot) kept++;
  if (prev?.verified && !sameSpot) reset++;
  try {
    venues.push(dbRowToVenue(row, prev?.verified === true && sameSpot));
  } catch (e) {
    problems.push((e as Error).message);
  }
}

if (problems.length > 0) {
  console.error('Import aborted, src/data/venues.json not changed:');
  for (const p of problems) console.error(`  ✖ ${p}`);
  process.exit(1);
}

const file: VenuesFile = {
  _note:
    'Generated by scripts/import-venues-db.ts from data/venues/eventall_venues.json. Do not edit by hand except for "verified". Venue data © OpenStreetMap contributors (ODbL).',
  venues,
};
writeFileSync(outPath, JSON.stringify(file, null, 2) + '\n');

const byCity = new Map<string, number>();
for (const v of venues) byCity.set(v.city, (byCity.get(v.city) ?? 0) + 1);
console.log(`Imported ${venues.length} venues → src/data/venues.json`);
for (const [city, n] of byCity) console.log(`  ${city}: ${n}`);
console.log(`  verified kept: ${kept}${reset ? `, verified reset because the coordinates changed: ${reset}` : ''}`);
console.log('Next: npm run validate:data');
